export const exportEngineerSummaryExample = (data: any[], userName: string) => {
  const columns: ExcelColumnConfig[] = [
    { header: 'Engineer Name', key: 'engineerName', width: 20 },
    { header: 'Project', key: 'project', width: 25 },
    { header: 'Tasks Completed', key: 'tasksCompleted', type: 'number', width: 15 },
    { header: 'Hours Logged', key: 'hoursLogged', type: 'number', width: 15 },
    { header: 'Efficiency %', key: 'efficiency', type: 'number', width: 12 },
    { header: 'Total Cost', key: 'totalCost', type: 'currency', width: 15 },
    { header: 'Last Updated', key: 'lastUpdated', type: 'date', width: 15 },
  ];

  const workbook = ExcelExporter.createWorkbook({
    sheetName: 'Engineer Summary',
    columns,
    data,
    title: 'SitePilot - Engineer Summary Report',
    includeMetadata: true,
    generatedBy: userName,
  });

  return workbook;
};

